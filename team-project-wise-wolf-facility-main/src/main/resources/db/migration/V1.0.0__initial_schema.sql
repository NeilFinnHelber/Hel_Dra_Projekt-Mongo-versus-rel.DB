create table billing_information
(
    cvv                    integer     not null,
    expiration_date        date        not null,
    billing_information_id bigint      not null,
    customer_id            bigint,
    card_number            varchar(16) not null,
    primary key (billing_information_id)
);

create table customer
(
    id               bigint       not null,
    address_city     varchar(255),
    address_country  varchar(255),
    address_street   varchar(255),
    address_zip_code varchar(255),
    email            varchar(255) not null unique,
    first_name       varchar(255),
    last_name        varchar(255),
    nickname         varchar(255) not null unique,
    permission       varchar(255) not null check (permission in ('Admin', 'Customer', 'Employee')),
    primary key (id)
);

create table film
(
    length       float4,
    release_year integer,
    id           bigint not null,
    title        varchar(255),
    primary key (id)
);

create table film_genres
(
    film_id bigint not null,
    genres  varchar(255) check (genres in
                                ('Action', 'Adventure', 'Animation', 'Comedy', 'Crime', 'Documentary', 'Drama',
                                 'Fantasy', 'Historical', 'Horror', 'Mystery', 'Romance', 'SciFi', 'Thriller',
                                 'Western'))
);

create table film_languages
(
    film_id   bigint not null,
    languages varchar(255) check (languages in ('English', 'German', 'French', 'Spanish', 'Japanese'))
);

create table order_placement
(
    actual_return_date date,
    order_date         date   not null,
    order_return_date  date   not null,
    customer_id        bigint not null,
    id                 bigint not null,
    order_id           bigint not null unique,
    primary key (id)
);

create table orders
(
    total_amount numeric(10, 2) not null,
    id           bigint         not null,
    order_date   timestamp(6)   not null,
    store_id     bigint         not null,
    primary key (id)
);

create table phone_numbers
(
    telephone_prefix integer      not null,
    id               bigint generated by default as identity,
    country          varchar(255) not null check (country in
                                                  ('Austria', 'USA', 'Germany', 'Switzerland', 'France', 'Japan',
                                                   'Spain', 'Greece', 'Italy')),
    phone_number     varchar(255),
    primary key (id)
);

create table series
(
    episodes     integer,
    length       float4,
    release_year integer,
    id           bigint not null,
    title        varchar(255),
    primary key (id)
);

create table series_genres
(
    series_id bigint not null,
    genres    varchar(255) check (genres in
                                  ('Action', 'Adventure', 'Animation', 'Comedy', 'Crime', 'Documentary', 'Drama',
                                   'Fantasy', 'Historical', 'Horror', 'Mystery', 'Romance', 'SciFi', 'Thriller',
                                   'Western'))
);

create table series_languages
(
    series_id bigint not null,
    languages varchar(255) check (languages in ('English', 'German', 'French', 'Spanish', 'Japanese'))
);

create table store
(
    id           bigint not null,
    phone_number varchar(255),
    primary key (id)
);

create table store_films
(
    film_id  bigint not null,
    store_id bigint not null,
    primary key (film_id, store_id)
);

create table store_series
(
    series_id bigint not null,
    store_id  bigint not null,
    primary key (series_id, store_id)
);

